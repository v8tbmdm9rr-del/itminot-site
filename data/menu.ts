/** Цена меньшего размера от базовой цены большего. */
export function smallSize(price: number): number {
  return Math.round((price * 0.8) / 10) * 10;
}

/** Размеры для неаполитанской пиццы: 25 см и 32 см. */
export function pizzaSizes(price: number) {
  return [
    { id: "25", label: "25 см", diameter: "25 см", price: smallSize(price) },
    { id: "32", label: "32 см", diameter: "32 см", price },
  ];
}

/** Размеры для римской пиццы: 20 см и 30 см. */
